/**
 * One-off generator: rasterizes Natural Earth land polygons (via the world-atlas package)
 * into a small ASCII density map used as the home page background.
 *   npx tsx scripts/gen-map.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
// @ts-expect-error no types installed for this dev-only script
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"));
const land = feature(topo, topo.objects.land) as { features?: any[]; geometry?: any };
const geoms: any[] = land.features ? land.features.map((f) => f.geometry) : [land.geometry];

const COLS = 130, ROWS = 30, TOP = 80, BOTTOM = -58, SX = 4, SY = 3;
type Ring = number[][];
const polys: Ring[][] = [];
for (const g of geoms) {
  if (g.type === "Polygon") polys.push(g.coordinates);
  else if (g.type === "MultiPolygon") polys.push(...g.coordinates);
}
const bbox = (ring: Ring) => ring.reduce((b, [x, y]) => [Math.min(b[0], x), Math.min(b[1], y), Math.max(b[2], x), Math.max(b[3], y)], [999, 999, -999, -999]);
const boxes = polys.map((p) => bbox(p[0]!));

function inRing(x: number, y: number, ring: Ring): boolean {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]!, [xj, yj] = ring[j]!;
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function isLand(lon: number, lat: number): boolean {
  for (let p = 0; p < polys.length; p++) {
    const b = boxes[p]!;
    if (lon < b[0]! || lon > b[2]! || lat < b[1]! || lat > b[3]!) continue;
    let inside = false;
    for (const ring of polys[p]!) if (inRing(lon, lat, ring)) inside = !inside; // outer ring minus holes
    if (inside) return true;
  }
  return false;
}

const rows: string[] = [];
for (let r = 0; r < ROWS; r++) {
  let line = "";
  for (let c = 0; c < COLS; c++) {
    let hits = 0;
    for (let sy = 0; sy < SY; sy++)
      for (let sx = 0; sx < SX; sx++) {
        const lon = -180 + ((c + (sx + 0.5) / SX) * 360) / COLS;
        const lat = TOP - ((r + (sy + 0.5) / SY) * (TOP - BOTTOM)) / ROWS;
        if (isLand(lon, lat)) hits++;
      }
    const f = hits / (SX * SY);
    line += f === 0 ? " " : f < 0.2 ? "." : f < 0.45 ? ":" : f < 0.7 ? "+" : "#";
  }
  rows.push(line.replace(/\s+$/, ""));
}

writeFileSync(
  new URL("../src/content/worldmap.ts", import.meta.url),
  `// Generated by scripts/gen-map.ts from Natural Earth land data. Do not edit by hand.
export const MAP_COLS = ${COLS};
export const MAP_ROWS = ${ROWS};
export const MAP_TOP = ${TOP};
export const MAP_BOTTOM = ${BOTTOM};
export const MAP_ROWS_TEXT: string[] = ${JSON.stringify(rows, null, 2)};
`,
);
console.log(rows.join("\n"));
